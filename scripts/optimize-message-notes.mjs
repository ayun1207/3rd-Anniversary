import { mkdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import sharp from 'sharp';

const root = resolve(import.meta.dirname, '..');
const output = join(root, 'images/messages/notes');
const topRowCounts = [2, 2, 3, 2, 3];
await mkdir(output, { recursive: true });

// 依既有整頁圖的五塊連續不透明區域量測位置，原圖本身已包含傾角。
async function notePositions(input, topRowCount) {
    const { data, info } = await sharp(input).resize({ width: 600 }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    const visited = new Uint8Array(info.width * info.height);
    const components = [];
    for (let start = 0; start < visited.length; start++) {
        if (visited[start] || data[start * 4 + 3] < 20) continue;
        const queue = [start];
        visited[start] = 1;
        let left = info.width, top = info.height, right = 0, bottom = 0;
        for (let head = 0; head < queue.length; head++) {
            const index = queue[head];
            const x = index % info.width, y = Math.floor(index / info.width);
            left = Math.min(left, x);
            right = Math.max(right, x);
            top = Math.min(top, y);
            bottom = Math.max(bottom, y);
            const neighbors = [];
            if (x > 0) neighbors.push(index - 1);
            if (x + 1 < info.width) neighbors.push(index + 1);
            if (y > 0) neighbors.push(index - info.width);
            if (y + 1 < info.height) neighbors.push(index + info.width);
            for (const neighbor of neighbors) {
                if (visited[neighbor] || data[neighbor * 4 + 3] < 20) continue;
                visited[neighbor] = 1;
                queue.push(neighbor);
            }
        }
        if (queue.length > 1000) components.push({ left, top, right, bottom });
    }
    if (components.length !== 5) throw new Error(`${input}: expected 5 separate notes, found ${components.length}`);
    components.sort((a, b) => a.top + a.bottom - b.top - b.bottom);
    const ordered = [components.slice(0, topRowCount), components.slice(topRowCount)].flatMap(row => row.sort((a, b) => a.left - b.left));
    return ordered.map(box => ({
        x: +(box.left / info.width * 100).toFixed(3),
        y: +(box.top / info.height * 100).toFixed(3),
        width: +((box.right - box.left + 1) / info.width * 100).toFixed(3),
        height: +((box.bottom - box.top + 1) / info.height * 100).toFixed(3)
    }));
}

const pages = [];
for (let page = 0; page < 5; page++) {
    const sheet = 27 + page;
    const reference = join(root, `images/messages/${sheet}.webp`);
    const metadata = await sharp(reference).metadata();
    const positions = await notePositions(reference, topRowCounts[page]);
    const notes = [];
    for (let slot = 0; slot < 5; slot++) {
        const id = page * 5 + slot + 1;
        const number = String(id).padStart(2, '0');
        const original = join(root, `artwork-originals/messages/${number}.png`);
        const trimmed = await sharp(original).rotate().trim({ threshold: 5 }).png().toBuffer();
        const full = await sharp(trimmed).resize({ width: 1200, height: 1200, fit: 'inside', withoutEnlargement: true })
            .webp({ quality: 90, alphaQuality: 95, effort: 6, smartSubsample: true }).toFile(join(output, `${number}.webp`));
        await sharp(trimmed).resize({ width: 320, height: 320, fit: 'inside', withoutEnlargement: true })
            .webp({ quality: 86, alphaQuality: 95, effort: 6, smartSubsample: true }).toFile(join(output, `${number}-320.webp`));
        notes.push({ id, number, ...positions[slot], imageWidth: full.width, imageHeight: full.height });
    }
    pages.push({ sheet, width: metadata.width, height: metadata.height, notes });
}

const moduleText = `// Generated by npm.cmd run optimize:message-notes. Do not edit by hand.
const assets = import.meta.glob('../../images/messages/**/*.webp', { eager: true, query: '?url', import: 'default' });
const pages = ${JSON.stringify(pages, null, 2)};
export const messagePages = pages.map(page => ({
    ...page,
    src: assets['../../images/messages/' + page.sheet + '.webp'],
    small: assets['../../images/messages/' + page.sheet + '-1200.webp'],
    notes: page.notes.map(note => ({
        ...note,
        src: assets['../../images/messages/notes/' + note.number + '.webp'],
        small: assets['../../images/messages/notes/' + note.number + '-320.webp']
    }))
}));
`;
await writeFile(join(root, 'src/data/messages.js'), moduleText, 'utf8');
console.log('Optimized 25 message notes and matched positions across 5 pages.');

import { mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises'
import { extname, join, parse, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import sharp from 'sharp'

const projectRoot = resolve(import.meta.dirname, '..')
const originalsDirectory = join(projectRoot, 'artwork-originals')
const artworkOutputDirectory = join(projectRoot, 'images', 'artworks')
const artworkManifestFile = join(projectRoot, 'src', 'data', 'artworks.js')
const supportedExtensions = new Set(['.avif', '.jpeg', '.jpg', '.png', '.tif', '.tiff', '.webp'])
const requestedIds = new Set(
  process.argv.slice(2).map(value => Number(value)).filter(id => Number.isInteger(id) && id >= 1 && id <= 24)
)
const isPartialRun = requestedIds.size > 0

async function writeWebp(input, output, { maxSize, quality }) {
  await mkdir(parse(output).dir, { recursive: true })

  const pipeline = sharp(input).rotate()
  if (maxSize) {
    pipeline.resize({
      width: maxSize,
      height: maxSize,
      withoutEnlargement: true,
      fit: 'inside'
    })
  }

  return pipeline
    .webp({ quality, alphaQuality: 95, effort: 6, smartSubsample: true })
    .toFile(output)
}

await writeWebp(
  join(projectRoot, 'images', 'intro-atmosphere-v2.png'),
  join(projectRoot, 'images', 'intro-atmosphere-v2.webp'),
  { maxSize: 1920, quality: 62 }
)

await mkdir(originalsDirectory, { recursive: true })
await mkdir(artworkOutputDirectory, { recursive: true })

const sourceEntries = await readdir(originalsDirectory, { withFileTypes: true })
const artworkSources = new Map()

for (const entry of sourceEntries) {
  if (!entry.isFile() || !supportedExtensions.has(extname(entry.name).toLowerCase())) continue
  const stem = parse(entry.name).name
  const match = stem.match(/^(?:photo)?(\d{1,2})(?:\D|$)/i)
  if (!match) continue

  const id = Number(match[1])
  if (id < 1 || id > 24) continue
  if (isPartialRun && !requestedIds.has(id)) continue
  if (artworkSources.has(id)) throw new Error(`Duplicate artwork id ${id} in ${originalsDirectory}`)
  artworkSources.set(id, join(originalsDirectory, entry.name))
}

if (isPartialRun) {
  const missingIds = Array.from(requestedIds).filter(id => !artworkSources.has(id))
  if (missingIds.length) {
    throw new Error(`Missing requested artwork id(s): ${missingIds.map(id => String(id).padStart(2, '0')).join(', ')}`)
  }
}

const processedArtworks = await Promise.all(Array.from(artworkSources, async ([id, input]) => {
  const number = String(id).padStart(2, '0')
  const [full, compact] = await Promise.all([
    writeWebp(input, join(artworkOutputDirectory, `${number}.webp`), {
      maxSize: 2000,
      quality: 84
    }),
    writeWebp(input, join(artworkOutputDirectory, `${number}-960.webp`), {
      maxSize: 960,
      quality: 80
    })
  ])

  return {
    id,
    number,
    full: `images/artworks/${number}.webp`,
    compact: `images/artworks/${number}-960.webp`,
    width: full.width,
    height: full.height,
    compactWidth: compact.width,
    compactHeight: compact.height,
    orientation: full.width > full.height ? 'landscape' : full.width < full.height ? 'portrait' : 'square'
  }
}))

processedArtworks.sort((a, b) => a.id - b.id)
const expectedOutputs = new Set(
  processedArtworks.flatMap(({ number }) => [`${number}.webp`, `${number}-960.webp`])
)
if (!isPartialRun) {
  const existingOutputs = await readdir(artworkOutputDirectory, { withFileTypes: true })
  await Promise.all(existingOutputs.map(async entry => {
    if (!entry.isFile() || !/^\d{2}(?:-960)?\.webp$/i.test(entry.name)) return
    if (!expectedOutputs.has(entry.name)) {
      await rm(join(artworkOutputDirectory, entry.name))
    }
  }))
}

let previousArtworkAssets = {}
if (isPartialRun) {
  try {
    const manifestUrl = `${pathToFileURL(artworkManifestFile).href}?updated=${Date.now()}`
    previousArtworkAssets = (await import(manifestUrl)).artworkAssets ?? {}
  } catch {
    previousArtworkAssets = {}
  }
}

const artworkAssets = {
  ...previousArtworkAssets,
  ...Object.fromEntries(processedArtworks.map(({ id, ...asset }) => [String(id), asset]))
}
const sortedArtworkAssets = Object.fromEntries(
  Object.entries(artworkAssets).sort(([a], [b]) => Number(a) - Number(b))
)
await writeFile(
  artworkManifestFile,
  `// Generated by npm.cmd run optimize:images. Do not edit by hand.\nexport const artworkAssets = ${JSON.stringify(sortedArtworkAssets, null, 2)}\n`,
  'utf8'
)

console.log(`Optimized ${processedArtworks.length} artwork image(s) from ${originalsDirectory}${isPartialRun ? ' (partial run)' : ''}.`)
for (const { number } of processedArtworks) {
  const full = await stat(join(artworkOutputDirectory, `${number}.webp`))
  const compact = await stat(join(artworkOutputDirectory, `${number}-960.webp`))
  console.log(`${number}: ${Math.round(full.size / 1024)} KB / ${Math.round(compact.size / 1024)} KB`)
}
